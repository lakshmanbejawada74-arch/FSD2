-- =====================================================================
-- CampusCare: Student Complaint Management System
-- Schema Definition Script (Safe & Non-Destructive)
-- =====================================================================

CREATE DATABASE IF NOT EXISTS `campuscare` 
DEFAULT CHARACTER SET utf8mb4 
COLLATE utf8mb4_0900_ai_ci;

USE `campuscare`;

-- 1. Students Table
CREATE TABLE IF NOT EXISTS `students` (
  `STUDENT_ID` varchar(30) NOT NULL,
  `FULL_NAME` varchar(100) NOT NULL,
  `DEPARTMENT` varchar(80) NOT NULL,
  `STUDY_YEAR` tinyint NOT NULL,
  `STUDENT_TYPE` varchar(15) NOT NULL DEFAULT 'DAY_SCHOLAR',
  `HOSTEL_NAME` varchar(100) DEFAULT NULL,
  `ROOM_NUMBER` varchar(20) DEFAULT NULL,
  `EMAIL` varchar(150) NOT NULL,
  `MOBILE` varchar(15) NOT NULL,
  `PASSWORD_HASH` varchar(255) NOT NULL,
  `ACCOUNT_STATUS` varchar(10) NOT NULL DEFAULT 'ACTIVE',
  `CREATED_AT` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`STUDENT_ID`),
  UNIQUE KEY `EMAIL` (`EMAIL`),
  CONSTRAINT `CK_STUDENT_HOSTEL` CHECK (
    ((`STUDENT_TYPE` = 'HOSTEL') AND (`HOSTEL_NAME` IS NOT NULL) AND (`ROOM_NUMBER` IS NOT NULL)) 
    OR 
    ((`STUDENT_TYPE` = 'DAY_SCHOLAR') AND (`HOSTEL_NAME` IS NULL) AND (`ROOM_NUMBER` IS NULL))
  ),
  CONSTRAINT `CK_STUDENT_STATUS` CHECK (`ACCOUNT_STATUS` IN ('ACTIVE','INACTIVE')),
  CONSTRAINT `CK_STUDENT_TYPE` CHECK (`STUDENT_TYPE` IN ('HOSTEL','DAY_SCHOLAR')),
  CONSTRAINT `CK_STUDENT_YEAR` CHECK (`STUDY_YEAR` BETWEEN 1 AND 6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- 2. Staff Table
CREATE TABLE IF NOT EXISTS `staff` (
  `STAFF_ID` varchar(30) NOT NULL,
  `FULL_NAME` varchar(100) NOT NULL,
  `DEPARTMENT` varchar(80) NOT NULL,
  `EMAIL` varchar(150) NOT NULL,
  `MOBILE` varchar(15) NOT NULL,
  `PASSWORD_HASH` varchar(255) NOT NULL,
  `ACCOUNT_STATUS` varchar(10) NOT NULL DEFAULT 'ACTIVE',
  `CREATED_AT` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`STAFF_ID`),
  UNIQUE KEY `EMAIL` (`EMAIL`),
  CONSTRAINT `CK_STAFF_STATUS` CHECK (`ACCOUNT_STATUS` IN ('ACTIVE','INACTIVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- 3. Admins Table
CREATE TABLE IF NOT EXISTS `admins` (
  `ADMIN_ID` varchar(30) NOT NULL,
  `USERNAME` varchar(80) NOT NULL,
  `PASSWORD_HASH` varchar(255) NOT NULL,
  `ACCOUNT_STATUS` varchar(10) NOT NULL DEFAULT 'ACTIVE',
  PRIMARY KEY (`ADMIN_ID`),
  UNIQUE KEY `USERNAME` (`USERNAME`),
  CONSTRAINT `CK_ADMIN_STATUS` CHECK (`ACCOUNT_STATUS` IN ('ACTIVE','INACTIVE'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- 4. Complaint Categories Table
CREATE TABLE IF NOT EXISTS `complaint_categories` (
  `CATEGORY_ID` int NOT NULL AUTO_INCREMENT,
  `CATEGORY_NAME` varchar(50) NOT NULL,
  `DESCRIPTION` varchar(255) DEFAULT NULL,
  `DEPARTMENT` varchar(80) NOT NULL,
  `ACTIVE` tinyint(1) NOT NULL DEFAULT '1',
  PRIMARY KEY (`CATEGORY_ID`),
  UNIQUE KEY `CATEGORY_NAME` (`CATEGORY_NAME`)
) ENGINE=InnoDB AUTO_INCREMENT=8 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- 5. Grievances (Complaints) Table
CREATE TABLE IF NOT EXISTS `grievances` (
  `GRIEVANCE_ID` bigint NOT NULL AUTO_INCREMENT,
  `STUDENT_ID` varchar(30) NOT NULL,
  `CATEGORY_ID` int NOT NULL,
  `TITLE` varchar(100) NOT NULL,
  `DESCRIPTION` varchar(1000) NOT NULL,
  `PRIORITY` varchar(10) NOT NULL DEFAULT 'MEDIUM',
  `STATUS` varchar(20) NOT NULL DEFAULT 'PENDING',
  `ASSIGNED_STAFF_ID` varchar(30) DEFAULT NULL,
  `CREATED_AT` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`GRIEVANCE_ID`),
  KEY `FK_GRIEVANCE_CATEGORY` (`CATEGORY_ID`),
  KEY `IDX_GRIEVANCE_STUDENT` (`STUDENT_ID`),
  KEY `IDX_GRIEVANCE_STAFF` (`ASSIGNED_STAFF_ID`),
  KEY `IDX_GRIEVANCE_STATUS` (`STATUS`),
  CONSTRAINT `FK_GRIEVANCE_CATEGORY` FOREIGN KEY (`CATEGORY_ID`) REFERENCES `complaint_categories` (`CATEGORY_ID`),
  CONSTRAINT `FK_GRIEVANCE_STAFF` FOREIGN KEY (`ASSIGNED_STAFF_ID`) REFERENCES `staff` (`STAFF_ID`),
  CONSTRAINT `FK_GRIEVANCE_STUDENT` FOREIGN KEY (`STUDENT_ID`) REFERENCES `students` (`STUDENT_ID`),
  CONSTRAINT `CK_GRIEVANCE_PRIORITY` CHECK (`PRIORITY` IN ('LOW','MEDIUM','HIGH')),
  CONSTRAINT `CK_GRIEVANCE_STATUS` CHECK (`STATUS` IN ('PENDING','ASSIGNED','IN_PROGRESS','RESOLVED','REJECTED','WITHDRAWN'))
) ENGINE=InnoDB AUTO_INCREMENT=1001 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- 6. Grievance Updates Table (Audit / History)
CREATE TABLE IF NOT EXISTS `grievance_updates` (
  `UPDATE_ID` bigint NOT NULL AUTO_INCREMENT,
  `GRIEVANCE_ID` bigint NOT NULL,
  `UPDATED_BY_ROLE` varchar(10) NOT NULL,
  `UPDATED_BY_ID` varchar(30) NOT NULL,
  `OLD_STATUS` varchar(20) DEFAULT NULL,
  `NEW_STATUS` varchar(20) NOT NULL,
  `REMARKS` varchar(500) DEFAULT NULL,
  `UPDATED_AT` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`UPDATE_ID`),
  KEY `IDX_UPDATE_GRIEVANCE` (`GRIEVANCE_ID`),
  CONSTRAINT `FK_UPDATE_GRIEVANCE` FOREIGN KEY (`GRIEVANCE_ID`) REFERENCES `grievances` (`GRIEVANCE_ID`),
  CONSTRAINT `CK_UPDATE_ROLE` CHECK (`UPDATED_BY_ROLE` IN ('STUDENT','STAFF','ADMIN')),
  CONSTRAINT `CK_UPDATE_STATUS` CHECK (`NEW_STATUS` IN ('PENDING','ASSIGNED','IN_PROGRESS','RESOLVED','REJECTED','WITHDRAWN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
